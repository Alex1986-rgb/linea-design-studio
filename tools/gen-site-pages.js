function page({ file, title, desc, h1, kicker, lead, body, crumb, jsonld, up, section, ogImage, ogType }) {
  const u = up || '../';
  section = section || (file.split('/')[0] || '');
  const canonical = `${BASE}/${file.replace(/index\.html$/, '')}`;
  const ld = (jsonld || []).map(o => `<script type="application/ld+json">${JSON.stringify(o)}</script>`).join('\n');
  const head = SHELL.head(u, { title, desc, canonical, ogTitle: String(h1).replace(/<[^>]*>/g, ''), ogDesc: String(lead).replace(/<[^>]*>/g, ''), ogType: ogType || 'article' })
    .replace(`${BASE}/assets/hero.jpg`, `${BASE}/${ogImage || 'assets/hero.jpg'}`);
  return `<!DOCTYPE html>
<html lang="ru">
<head>
${head}
${ld}
</head>
<body>
${SHELL.beta(u)}

${SHELL.header(u, section)}
${SHELL.crumbsAuto(u, section, /\/index\.html$/.test(file) && file.split('/').length === 2 ? null : String(h1).replace(/<[^>]*>/g, ''))}

<section class="blk hero-page">
  <div class="wrap">
    <div class="kicker">${crumb || kicker}</div>
    <h1>${h1}</h1>
    <p class="lead-page">${lead}</p>
  </div>
</section>

${body}

${SHELL.ctaBlock(u, section)}

${SHELL.sticky(u)}

${SHELL.footer(u, section)}
</body>
</html>
`;
}
